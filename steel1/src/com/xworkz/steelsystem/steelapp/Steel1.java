package com.xworkz.steelsystem.steelapp;

public class Steel1
{

        private String brand;
        private String type;
        private double price;
        private String material;
        private String color;
        private boolean isRustProof;
        private String madeInCountry;

        public void setBrand(String brand)
        {
            this.brand = brand;
        }

        public String getBrand()
        {
            return brand;
        }

        public void setType(String type)
        {
            this.type = type;
        }

        public String getType()
        {
            return type;
        }

        public void setPrice(double price)
        {
            this.price = price;
        }

        public double getPrice()
        {
            return price;
        }

        public void setMaterial(String material)
        {
            this.material = material;
        }

        public String getMaterial() {
            return material;
        }

        public void setColor(String color)
        {
            this.color = color;
        }

        public String getColor()
        {
            return color;
        }

        public void setIsRustProof(boolean isRustProof)
        {
            this.isRustProof = isRustProof;
        }

        public boolean getIsRustProof()
        {
            return isRustProof;
        }

        public void setMadeInCountry(String madeInCountry)
        {
            this.madeInCountry = madeInCountry;
        }

        public String getMadeInCountry()
        {
            return madeInCountry;
        }
    }



