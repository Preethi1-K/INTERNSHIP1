package com.xworkz.mobilecasesystem.mobileapp;

public class Mobilecase
{


        private String brand;
        private String material;
        private String color;
        private double price;
        private boolean isCompatibleWithWirelessCharging;
        private String model;
        private String type;

        public void setBrand(String brand)
        {
            this.brand = brand;
        }

        public String getBrand()
        {
            return brand;
        }

        public void setMaterial(String material)
        {
            this.material = material;
        }

        public String getMaterial()
        {
            return material;
        }

        public void setColor(String color)
        {
            this.color = color;
        }

        public String getColor()
        {
            return color;
        }

        public void setPrice(double price)
        {
            this.price = price;
        }

        public double getPrice()
        {
            return price;
        }

        public void setIsCompatibleWithWirelessCharging(boolean isCompatibleWithWirelessCharging)
        {
            this.isCompatibleWithWirelessCharging = isCompatibleWithWirelessCharging;
        }

        public boolean getIsCompatibleWithWirelessCharging()
        {
            return isCompatibleWithWirelessCharging;
        }

        public void setModel(String model)
        {
            this.model = model;
        }

        public String getModel()
        {
            return model;
        }

        public void setType(String type)
        {
            this.type = type;
        }

        public String getType()
        {
            return type;
        }
    }


